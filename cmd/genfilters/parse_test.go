func TestEscape(t *testing.T) {
	for _, name := range []string{
		"plain.txt", "we*rd[1]/{x}.txt", `back\slash`, "q?", "trailing ", "日本語", "nbsp ", " leading",
	} {
		glob := escape(name)
		got, err := unescape(glob)
		require.NoError(t, err, glob)
		assert.Equal(t, name, got, glob)
		// The escaped glob, as read from a trimmed line, matches the name literally
		re, err := filter.GlobPathToRegexp(strings.TrimSpace("/"+glob), false)
		require.NoError(t, err, glob)
		assert.True(t, re.MatchString(name), "%q doesn't match %q", glob, name)
	}
	assert.Equal(t, "trailing[ ]", escape("trailing "))
	_, err := unescape("a*b")
	assert.ErrorContains(t, err, "matches more than one name")
}

func TestParseRoundTrip(t *testing.T) {
	mo, err := newModel(excludeOthers)
	require.NoError(t, err)
	mo.header = []string{"# my filters", ""}
	spaceEnd := "space /end "
	for key, include := range map[string]bool{
		"docs/": true, "docs/sub/": false, "docs/sub/deep.md": true, "we*rd[1]/{x}.txt": true, spaceEnd: true,
	} {
		require.NoError(t, mo.set(key, include))
	}
	got, hasRules, err := parse(mo.lines())
	require.NoError(t, err)
	assert.True(t, hasRules)
	assert.Equal(t, mo.mode, got.mode)
	assert.Equal(t, mo.selected, got.selected)
	assert.Equal(t, mo.header, got.header)
	assert.Equal(t, mo.lines(), got.lines())
}

func TestParse(t *testing.T) {
	for _, test := range []struct {
		name     string
		in       string
		mode     mode
		hasRules bool
		selected map[string]bool
		header   int
	}{{
		name: "empty",
	}, {
		name:     "no catch-all includes others",
		in:       "- /a.txt",
		hasRules: true, selected: map[string]bool{"a.txt": false},
	}, {
		name:     "exclude others",
		in:       "+ /docs/**\n- **",
		mode:     excludeOthers,
		hasRules: true, selected: map[string]bool{"docs/": true},
	}, {
		name: "old genfilters output",
		in: `# Filters for fixture generated by rclone genfilters 2026-10-28 14:09:27

# Example usage:
# rclone tree "fixture" --filter-from "baseline-rules.txt"

; REMINDERS:
- /tmp/**
- /a.txt
+ /*
+ **
`,
		hasRules: true, selected: map[string]bool{"tmp/": false, "a.txt": false}, header: 6,
	}, {
		name:     "reset",
		in:       "- /a.txt\n!\n+ /b.txt\n- **",
		mode:     excludeOthers,
		hasRules: true, selected: map[string]bool{"b.txt": true},
	}, {
		name:     "reset clears the catch-all",
		in:       "- /a.txt\n- **\n!\n- /b.txt",
		hasRules: true, selected: map[string]bool{"b.txt": false},
	}, {
		name:     "nested",
		in:       "  + /tmp/keep.txt  \n- /tmp/**\n+ **",
		hasRules: true, selected: map[string]bool{"tmp/keep.txt": true, "tmp/": false},
	}} {
		t.Run(test.name, func(t *testing.T) {
			lines := strings.Split(test.in, "\n")
			mo, hasRules, err := parse(lines)
			require.NoError(t, err)
			assert.Equal(t, test.mode, mo.mode)
			assert.Equal(t, test.hasRules, hasRules)
			if test.selected == nil {
				test.selected = map[string]bool{}
			}
			assert.Equal(t, test.selected, mo.selected)
			assert.Len(t, mo.header, test.header)
			checkSame(t, mo, lines)
		})
	}
}

func TestParseErrors(t *testing.T) {
	for _, test := range []struct {
		in   string
		line int
		want string
	}{
		{"- *.tmp", 1, `must start with "/"`},
		{"- /tmp/*.tmp", 1, "matches more than one name"},
		{"- /tmp/*", 1, `use "/dir/**" for a directory and everything in it`},
		{"- /tmp/sub/*", 1, `use "/dir/**"`},
		{"- /tmp/a*", 1, "matches more than one name"},
		{"- /{{.*}}", 1, "matches more than one name"},
		{"- /tmp/", 1, `use "/dir/**"`},
		{"- /**", 1, "matches more than one name"},
		{"- /[ab].txt", 1, "matches more than one name"},
		{"/tmp", 1, "malformed rule"},
		{"- /a[", 1, "mismatched"},
		{"- /a.txt\n# comment", 2, "comments must come before"},
		{"- **\n- /a.txt", 2, "after the catch-all"},
		{"- /a.txt\n+ /a.txt", 2, "duplicates the rule on line 1"},
		{"- /tmp/**\n+ /tmp/keep.txt", 2, `never used: the rule on line 1 for "tmp/"`},
		{"- /*\n+ **", 1, `"/*" must match the catch-all`},
		{"+ /*", 1, `"/*" must match the catch-all`},
		{"+ /*\n- /a.txt\n+ **", 2, `never used: the rule on line 1 for "/*"`},
	} {
		t.Run(test.in, func(t *testing.T) {
			_, _, err := parse(strings.Split(test.in, "\n"))
			require.Error(t, err)
			var lineErr *lineError
			require.ErrorAs(t, err, &lineErr)
			assert.Equal(t, test.line, lineErr.line)
			assert.ErrorContains(t, err, test.want)
		})
	}
}

// TestParseEveryPunctuation checks names written by escape are read back
// unchanged, including space at the end, which filter files trim
func TestParseEveryPunctuation(t *testing.T) {
	var chars []rune
	for c := rune(' '); c <= '~'; c++ {
		if !unicode.IsLetter(c) && !unicode.IsDigit(c) && c != '/' {
			chars = append(chars, c)
		}
	}
	chars = append(chars, ' ', '　')
	for _, c := range chars {
		for _, name := range []string{"a" + string(c) + "b", "ab" + string(c)} {
			mo, _, err := parse([]string{"- /" + escape(name)})
			require.NoError(t, err, name)
			assert.Equal(t, map[string]bool{name: false}, mo.selected, name)
		}
	}
}

// TestParseMatchesEngine checks parse against rclone's filter engine on
// random rule files. Rules it accepts, and the rules it writes back,
// must include the same things the file did, and a rule it rejects as
// unused must decide nothing.
func TestParseMatchesEngine(t *testing.T) {
	keys := []string{"a.txt", "b.txt", "d/", "d/x.txt", "d/e/", "d/e/y.txt", "d/e/z.txt", "f/", "f/w.txt"}
	probes := append([]string{"zz", "d/zz", "d/e/zz", "f/zz", "g/", "g/zz"}, keys...)
	var candidates []string
	for _, k := range keys {
		candidates = append(candidates, "+ "+glob(k), "- "+glob(k))
	}
	rnd := rand.New(rand.NewSource(1))
	counts := map[string]int{}
	for range 5000 {
		var lines []string
		for range 1 + rnd.Intn(6) {
			lines = append(lines, candidates[rnd.Intn(len(candidates))])
		}
		insert := func(line string) {
			i := rnd.Intn(len(lines) + 1)
			lines = append(lines[:i], append([]string{line}, lines[i:]...)...)
		}
		if rnd.Intn(10) < 7 {
			insert(sign(rnd.Intn(2) == 0) + " **")
		}
		if rnd.Intn(10) < 2 {
			insert(sign(rnd.Intn(2) == 0) + " /*")
		}
		if rnd.Intn(20) < 1 {
			insert("!")
		}
		want := engine(t, lines)
		mo, _, err := parse(lines)
		if err == nil {
			counts["accepted"]++
			written := engine(t, mo.lines())
			for _, p := range probes {
				require.Equal(t, want(p), mo.included(p), "included(%q) with %q", p, lines)
				require.Equal(t, want(p), written(p), "%q with %q written as %q", p, lines, mo.rules())
			}
			continue
		}
		var lineErr *lineError
		require.ErrorAs(t, err, &lineErr)
		msg := lineErr.err.Error()
		switch {
		case strings.HasPrefix(msg, "never used"), strings.HasPrefix(msg, "duplicates"), strings.HasPrefix(msg, "rules after the catch-all"):
			counts[strings.Fields(msg)[0]]++
			without := engine(t, append(append([]string(nil), lines[:lineErr.line-1]...), lines[lineErr.line:]...))
			for _, p := range probes {
				require.Equal(t, want(p), without(p), "line %d of %q is said to be unused but decides %q", lineErr.line, lines, p)
			}
		default:
			counts["other"]++
		}
	}
	t.Log(counts)
	for _, kind := range []string{"accepted", "never", "duplicates", "rules"} {
		assert.Greater(t, counts[kind], 50, kind)
	}
}
